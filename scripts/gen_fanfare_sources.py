#!/usr/bin/env python3
"""Regenerate fanfare_sources.go from scripts/fanfare_sources.json.

Usage: python3 scripts/gen_fanfare_sources.py   (run from the repo root)

Each track lists: kind, sha256 (of the file at url), url (upload.wikimedia.org), license,
title, attribution. The Commons file page is derived from the url's file name. Check the licence
on that page (performer must be a US government band, or CC0/CC BY by the performer) before
adding a track, download it, pin `shasum -a 256`, then regenerate.
"""
import json, os, sys, urllib.parse

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
pairs = json.load(open(os.path.join(here, "fanfare_sources.json"), encoding="utf-8"))
q = lambda s: json.dumps(s, ensure_ascii=False)

out = ["// Generated by scripts/gen_fanfare_sources.py from scripts/fanfare_sources.json; edit the JSON, not this file.",
       "", "package main", "",
       "// Only public domain, CC0 and CC-BY recordings (composition and recording) are listed.",
       "var builtinPairs = []fanfarePair{"]
for p in pairs:
    out.append("\t{Name: %s, Label: %s, Tracks: []fanfareTrack{" % (q(p["name"]), q(p["label"])))
    for t in p["tracks"]:
        assert t["url"].startswith("https://upload.wikimedia.org/"), t["url"]
        assert len(t["sha256"]) == 64, t
        fname = urllib.parse.unquote(t["url"].rsplit("/", 1)[1])
        source = "https://commons.wikimedia.org/wiki/File:" + urllib.parse.quote(fname, safe="()!,'~")
        out.append("\t\t{Kind: %s, Ext: %s, SHA256: %s, URL: %s, Source: %s, License: %s, Attribution: %s, Title: %s}," % (
            q(t["kind"]), q(t["url"].rsplit(".", 1)[1]), q(t["sha256"]), q(t["url"]), q(source), q(t["license"]), q(t["attribution"]), q(t["title"])))
    out.append("\t}},")
out.append("}")
open(os.path.join(root, "fanfare_sources.go"), "w", encoding="utf-8").write("\n".join(out) + "\n")
